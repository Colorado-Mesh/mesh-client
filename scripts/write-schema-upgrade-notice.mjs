#!/usr/bin/env node
/**
 * Write installer / package notice files when MESH_CLIENT_SCHEMA_BUMPED=1.
 *
 * When schema is not bumped: remove the packaged SCHEMA-UPGRADE.txt and replace
 * any bumped schema-upgrade-notice.nsh with an empty stub. installer.nsh always
 * `!include`s the .nsh, so it must exist (even without a define) or NSIS warns
 * 7000 and fails the build under `-WX`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const RESOURCES = path.join(ROOT, 'resources');
const TXT_NAME = 'SCHEMA-UPGRADE.txt';
const NSH_NAME = 'schema-upgrade-notice.nsh';
/** Empty include so installer.nsh never warns under -WX when schema is not bumped. */
const NSH_STUB =
  `; Generated by scripts/write-schema-upgrade-notice.mjs — no schema bump.\n` +
  `; Empty on purpose: installer.nsh includes this file unconditionally.\n`;

/**
 * @param {{
 *   bumped: boolean
 *   currSchema: number
 *   prevSchema: number | null
 *   prevTag: string | null
 * }} opts
 */
export function formatSchemaUpgradeNoticeText(opts) {
  const prev =
    opts.prevSchema != null && opts.prevTag
      ? `${opts.prevTag} (schema ${opts.prevSchema})`
      : opts.prevSchema != null
        ? `schema ${opts.prevSchema}`
        : 'the previous official release';
  return (
    `Mesh-Client database schema upgrade\n` +
    `====================================\n\n` +
    `This build uses SQLite schema ${opts.currSchema}.\n` +
    `Last compared official release: ${prev}.\n\n` +
    `Launching this build against an existing database will upgrade it.\n` +
    `You cannot downgrade to an older Mesh-Client that only supports the\n` +
    `previous schema while keeping the same database.\n\n` +
    `On first launch, Mesh-Client shows a Quit / Upgrade dialog before\n` +
    `changing the database. Choose Quit to exit without upgrading.\n`
  );
}

/**
 * @param {string} message
 * NSIS MessageBox detail — keep ASCII; use $\r$\n for newlines in the include.
 */
export function formatNsisSchemaUpgradeInclude(message) {
  const escaped = message
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n')
    .split('\n')
    .map((line) => line.replace(/\$/g, '$$').replace(/"/g, '$\\"'))
    .join('$\\r$\\n');
  return (
    `; Generated by scripts/write-schema-upgrade-notice.mjs — do not edit.\n` +
    `!define MESH_CLIENT_SCHEMA_UPGRADE_NOTICE "${escaped}"\n`
  );
}

/**
 * @param {NodeJS.ProcessEnv} [env]
 * @param {string} [resourcesDir]
 */
export function writeSchemaUpgradeNoticeFiles(env = process.env, resourcesDir = RESOURCES) {
  const bumped = env.MESH_CLIENT_SCHEMA_BUMPED === '1' || env.MESH_CLIENT_SCHEMA_BUMPED === 'true';
  const txtPath = path.join(resourcesDir, TXT_NAME);
  const nshPath = path.join(resourcesDir, NSH_NAME);

  if (!bumped) {
    if (fs.existsSync(txtPath)) fs.unlinkSync(txtPath);
    fs.mkdirSync(resourcesDir, { recursive: true });
    fs.writeFileSync(nshPath, NSH_STUB, 'utf8');
    console.debug(
      '[write-schema-upgrade-notice] No schema bump; notice text cleared, NSIS stub kept',
    );
    return { bumped: false, txtPath, nshPath };
  }

  const currSchema = Number(env.MESH_CLIENT_SCHEMA_CURR ?? '');
  const prevRaw = env.MESH_CLIENT_SCHEMA_PREV ?? '';
  const prevSchema = prevRaw !== '' && /^\d+$/.test(prevRaw) ? Number(prevRaw) : null;
  const prevTag =
    typeof env.MESH_CLIENT_SCHEMA_PREV_TAG === 'string' && env.MESH_CLIENT_SCHEMA_PREV_TAG
      ? env.MESH_CLIENT_SCHEMA_PREV_TAG
      : null;

  if (!Number.isInteger(currSchema) || currSchema < 1) {
    throw new Error('MESH_CLIENT_SCHEMA_CURR must be a positive integer when schema is bumped');
  }

  const text = formatSchemaUpgradeNoticeText({
    bumped: true,
    currSchema,
    prevSchema,
    prevTag,
  });
  fs.mkdirSync(resourcesDir, { recursive: true });
  fs.writeFileSync(txtPath, text, 'utf8');
  fs.writeFileSync(nshPath, formatNsisSchemaUpgradeInclude(text), 'utf8');
  console.debug(`[write-schema-upgrade-notice] Wrote ${TXT_NAME} and ${NSH_NAME}`);
  return { bumped: true, txtPath, nshPath, text };
}

const entry = process.argv[1] ? pathToFileURL(process.argv[1]).href : '';
if (entry && import.meta.url === entry) {
  try {
    writeSchemaUpgradeNoticeFiles();
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    console.error(`[write-schema-upgrade-notice] ${detail}`);
    process.exit(1);
  }
}
