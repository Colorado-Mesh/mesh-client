/**
 * Native plugin contracts for the Mesh Client mobile apps.
 *
 * These four Capacitor plugins are implemented natively (Kotlin in `mobile/android`, Swift in
 * `mobile/ios`) and in Node for the browser test harness (`mobile/scripts/web-bridge.mjs` for
 * MeshNet, `mobile/src/bridge/web/*` for the rest). The host worker shims
 * (`mobile/src/host/shims/**`) are the only callers, through `callNative` / `onNativeEvent`.
 *
 * Conventions:
 * - Binary payloads are base64 strings (`…B64`).
 * - Stream/socket ids are generated by the caller (`id`) so events that arrive before the call
 *   resolves are never lost.
 * - Errors reject the call with a message; socket/HTTP failures put the Node error code at the
 *   start of the message when one applies (`ECONNREFUSED …`, `ETIMEDOUT …`, `ENOTFOUND …`,
 *   `CERT_HAS_EXPIRED …`) so the shims can surface Node-compatible `err.code`.
 * - Events are delivered with `notifyListeners(eventName, data)`.
 */

// ─── MeshNet: sockets, DNS, HTTP, WebSocket ────────────────────────────────────

export interface TcpConnectOptions {
  id: string;
  host: string;
  port: number;
  tls: boolean;
  /** SNI / hostname verification name (omit for IP literals). */
  servername?: string;
  rejectUnauthorized: boolean;
  /** Extra trust anchors (PEM or DER, base64 of the file bytes). */
  caB64?: string | string[];
  /** Client certificate (PEM/DER) + key, or a PKCS#12 bundle, for mutual TLS (TAK). */
  certB64?: string;
  keyB64?: string;
  pfxB64?: string;
  passphrase?: string;
  alpn?: string[];
  noDelay: boolean;
  keepAlive: boolean;
  keepAliveDelayMs?: number;
  /** Connect timeout; default 20 000 ms. */
  timeoutMs?: number;
}

export interface TcpConnectResult {
  localAddress?: string;
  localPort?: number;
  remoteAddress?: string;
  remotePort?: number;
  remoteFamily?: 'IPv4' | 'IPv6';
  authorized?: boolean;
  authorizationError?: string;
  alpnProtocol?: string;
}

export interface TcpListenOptions {
  id: string;
  host: string;
  port: number;
  tls?: {
    certB64?: string;
    keyB64?: string;
    caB64?: string;
    pfxB64?: string;
    passphrase?: string;
    requestCert: boolean;
    rejectUnauthorized: boolean;
  };
}

export interface HttpRequestOptions {
  id: string;
  url: string;
  method: string;
  headers: Record<string, string>;
  bodyB64?: string;
  followRedirects?: boolean;
  /**
   * Header `x-mesh-pinned-address` (inside `headers`) carries an IP the host already validated
   * as public; the native client must connect to that address (keeping Host/SNI = URL host) and
   * strip the header before sending. Implementations that cannot pin connect normally.
   */
}

export interface HttpStartResult {
  status: number;
  statusText?: string;
  /** Lower-case header names; repeated headers joined with ", ". */
  headers: Record<string, string>;
  /** Final URL after redirects. */
  url?: string;
}

export interface WsConnectOptions {
  id: string;
  url: string;
  headers: Record<string, string>;
  protocols: string[];
  timeoutMs?: number;
  rejectUnauthorized: boolean;
}

export interface MeshNetPlugin {
  tcpConnect(o: TcpConnectOptions): Promise<TcpConnectResult>;
  tcpWrite(o: { id: string; dataB64: string }): Promise<void>;
  /** Half-close (FIN) after queued writes. */
  tcpEnd(o: { id: string }): Promise<void>;
  tcpDestroy(o: { id: string }): Promise<void>;
  tcpSetOptions(o: { id: string; noDelay?: boolean; keepAlive?: boolean }): Promise<void>;
  tcpListen(o: TcpListenOptions): Promise<{ port: number; host?: string }>;
  tcpServerClose(o: { id: string }): Promise<void>;

  udpCreate(o: { id: string; type: 'udp4' | 'udp6'; reuseAddr: boolean }): Promise<void>;
  udpBind(o: {
    id: string;
    port: number;
    address: string;
  }): Promise<{ address: string; port: number }>;
  udpSend(o: { id: string; dataB64: string; port: number; address: string }): Promise<void>;
  udpClose(o: { id: string }): Promise<void>;
  udpSetOptions(o: {
    id: string;
    broadcast?: boolean;
    multicastTtl?: number;
    multicastLoopback?: boolean;
  }): Promise<void>;
  udpAddMembership(o: { id: string; group: string; iface?: string }): Promise<void>;
  udpDropMembership(o: { id: string; group: string; iface?: string }): Promise<void>;

  dnsLookup(o: {
    hostname: string;
    family: 0 | 4 | 6;
  }): Promise<{ addresses: { address: string; family: 4 | 6 }[] }>;

  /** Resolves once status + headers arrive; the body streams as httpData events. */
  httpRequest(o: HttpRequestOptions): Promise<HttpStartResult>;
  httpCancel(o: { id: string }): Promise<void>;

  /** Resolves when the request is started; `wsOpen` reports the upgrade. */
  wsConnect(o: WsConnectOptions): Promise<void>;
  wsSend(o: { id: string; text?: string; dataB64?: string }): Promise<void>;
  wsClose(o: { id: string; code: number; reason: string }): Promise<void>;
}

export interface MeshNetEvents {
  tcpData: { id: string; dataB64: string };
  /** Peer sent FIN. */
  tcpEnd: { id: string };
  /** Socket fully closed; `error` set when it closed because of an error. */
  tcpClose: { id: string; error?: string };
  tcpAccept: { serverId: string; id: string } & TcpConnectResult;
  udpMessage: { id: string; dataB64: string; address: string; port: number };
  udpError: { id: string; message: string };
  httpData: { id: string; dataB64: string };
  httpEnd: { id: string };
  httpError: { id: string; message: string };
  wsOpen: { id: string; protocol?: string };
  wsMessage: { id: string; text?: string; dataB64?: string };
  wsClose: { id: string; code: number; reason: string };
  wsError: { id: string; message: string };
}

// ─── MeshDevice: device key, app info, fold posture, keep-awake ───────────────

export interface NativeFoldFeature {
  /** Fold bounds in CSS px (physical px / density), relative to the WebView. */
  left: number;
  top: number;
  right: number;
  bottom: number;
  orientation: 'vertical' | 'horizontal';
  state: 'flat' | 'half-opened';
  /** Jetpack `FoldingFeature.isSeparating` / iPhone Duo active division region. */
  separating: boolean;
}

export interface MeshDevicePlugin {
  /**
   * 32-byte random key (hex) generated once and stored under hardware-backed protection
   * (Android Keystore-wrapped / iOS Keychain `WhenUnlockedThisDeviceOnly`). Backs Electron
   * `safeStorage` on mobile.
   */
  getSecureKey(): Promise<{ keyHex: string }>;
  getInfo(): Promise<{
    appVersion: string;
    sidecarAvailable: boolean;
    locale: string;
    model?: string;
    osVersion?: string;
  }>;
  getFoldState(): Promise<{ folds: NativeFoldFeature[] }>;
  /** Keep the screen awake while a radio operation needs it (firmware flash, long transfers). */
  keepAwake(o: { enabled: boolean }): Promise<void>;
  /**
   * Keep radio links alive while the app is in the background. Android: a `connectedDevice`
   * foreground service with an ongoing notification (title/text). iOS: no-op (BLE uses the
   * `bluetooth-central` background mode; sockets follow the system background policy).
   */
  setBackgroundMode(o: { enabled: boolean; title?: string; text?: string }): Promise<void>;
}

export interface MeshDeviceEvents {
  foldChanged: { folds: NativeFoldFeature[] };
}

// ─── MeshUsbSerial (Android only) ──────────────────────────────────────────────

export interface UsbSerialDevice {
  /** Stable for the attachment (Android `UsbDevice.deviceName`). */
  deviceId: string;
  vendorId: number;
  productId: number;
  productName?: string;
  manufacturerName?: string;
  serialNumber?: string;
}

export interface MeshUsbSerialPlugin {
  /** USB devices with a serial driver (CDC-ACM, CP210x, CH34x, FTDI, PL2303, …). */
  listDevices(): Promise<{ devices: UsbSerialDevice[] }>;
  requestPermission(o: { deviceId: string }): Promise<{ granted: boolean }>;
  open(o: {
    deviceId: string;
    baudRate: number;
    dataBits: number;
    stopBits: number;
    parity: 'none' | 'even' | 'odd';
  }): Promise<{ portId: string }>;
  write(o: { portId: string; dataB64: string }): Promise<void>;
  close(o: { portId: string }): Promise<void>;
  setSignals(o: { portId: string; dtr?: boolean; rts?: boolean; brk?: boolean }): Promise<void>;
  getSignals(o: {
    portId: string;
  }): Promise<{ dcd: boolean; cts: boolean; ri: boolean; dsr: boolean }>;
}

export interface MeshUsbSerialEvents {
  data: { portId: string; dataB64: string };
  closed: { portId: string; error?: string };
  attached: { device: UsbSerialDevice };
  detached: { device: UsbSerialDevice };
}

// ─── MeshProcess: the Reticulum sidecar ────────────────────────────────────────

export interface MeshProcessPlugin {
  /**
   * Start the bundled Reticulum sidecar (`program` is always `reticulum-sidecar`). Android runs
   * the packaged executable from the app's native library directory; iOS runs the sidecar library
   * on a background thread. stdin/stdout/stderr semantics match a child process.
   */
  spawn(o: {
    id: string;
    program: 'reticulum-sidecar';
    args: string[];
    env: Record<string, string>;
  }): Promise<{ pid: number }>;
  writeStdin(o: { id: string; dataB64: string }): Promise<void>;
  closeStdin(o: { id: string }): Promise<void>;
  kill(o: { id: string; signal: string }): Promise<void>;

  /**
   * The real directory shared by main and the sidecar (Reticulum config + storage). The host maps
   * the virtual `/data/user/reticulum` to it in sidecar arguments. Android:
   * `<filesDir>/mesh-reticulum`; iOS: `<Application Support>/mesh-reticulum`. Created if missing.
   */
  getSharedDir(): Promise<{ path: string }>;
  /** Recursive listing under the shared dir (`path` relative, '' = root); files only. */
  sharedList(o: {
    path: string;
  }): Promise<{ files: { path: string; size: number; mtimeMs: number }[] }>;
  sharedRead(o: { path: string }): Promise<{ dataB64: string }>;
  /** Atomic replace (write temp + rename); creates parent directories. */
  sharedWrite(o: { path: string; dataB64: string }): Promise<void>;
  /** Removes a file or directory tree; no error when missing. */
  sharedRemove(o: { path: string }): Promise<void>;
}

export interface MeshProcessEvents {
  stdout: { id: string; dataB64: string };
  stderr: { id: string; dataB64: string };
  exit: { id: string; code: number | null; signal: string | null };
}
