#!/usr/bin/env bash
# Links the optional in-process Reticulum sidecar into the App target.
#
# Run after `node mobile/scripts/build-sidecar.mjs ios` has written
# mobile/ios/App/MeshReticulum.xcframework. Writes the gitignored mobile/ios/mesh-sidecar.xcconfig
# (included by mesh.xcconfig) with the header/library search paths of the device and simulator
# slices, so `canImport(MeshReticulum)` turns MeshProcess.spawn on. Without the xcframework the
# file is removed and the app builds with sidecarAvailable=false.
#
# Extra linker inputs printed by the sidecar build ("link with: …") can be appended through
# MESH_SIDECAR_EXTRA_LDFLAGS.
set -euo pipefail

ios="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
framework="$ios/App/MeshReticulum.xcframework"
out="$ios/mesh-sidecar.xcconfig"

if [ ! -d "$framework" ]; then
  rm -f "$out"
  echo "configure-sidecar: $framework not found; sidecar disabled"
  exit 0
fi

device=""
simulator=""
for slice in "$framework"/ios-*; do
  [ -d "$slice" ] || continue
  name="$(basename "$slice")"
  case "$name" in
    *-maccatalyst) ;;
    *-simulator) simulator="$name" ;;
    *) device="$name" ;;
  esac
done
if [ -z "$device" ] || [ -z "$simulator" ]; then
  echo "configure-sidecar: $framework needs an iOS device and an iOS simulator slice" >&2
  exit 1
fi
for slice in "$device" "$simulator"; do
  if [ ! -f "$framework/$slice/Headers/module.modulemap" ] || [ ! -f "$framework/$slice/libmesh_reticulum.a" ]; then
    echo "configure-sidecar: $slice lacks Headers/module.modulemap or libmesh_reticulum.a" >&2
    exit 1
  fi
done

# SRCROOT is mobile/ios/App (the directory of App.xcodeproj).
cat > "$out" << XCCONFIG
// Generated by mobile/ios/scripts/configure-sidecar.sh; do not edit (gitignored).
MESH_SIDECAR_SWIFT_INCLUDE_PATHS[sdk=iphoneos*] = \$(SRCROOT)/MeshReticulum.xcframework/$device/Headers
MESH_SIDECAR_SWIFT_INCLUDE_PATHS[sdk=iphonesimulator*] = \$(SRCROOT)/MeshReticulum.xcframework/$simulator/Headers
MESH_SIDECAR_LIBRARY_SEARCH_PATHS[sdk=iphoneos*] = \$(SRCROOT)/MeshReticulum.xcframework/$device
MESH_SIDECAR_LIBRARY_SEARCH_PATHS[sdk=iphonesimulator*] = \$(SRCROOT)/MeshReticulum.xcframework/$simulator
MESH_SIDECAR_LDFLAGS = -lmesh_reticulum -framework CoreFoundation -framework Security -framework SystemConfiguration -liconv -lresolv -lc++ ${MESH_SIDECAR_EXTRA_LDFLAGS:-}
XCCONFIG
echo "configure-sidecar: wrote $out ($device, $simulator)"
